#!/usr/bin/env bash
# ==============================================================================
# Khepri Automated Installer for Debian / Ubuntu / Raspberry Pi OS (ARM64 & x86)
# ==============================================================================
# Sets up prerequisites, virtualenv, dependencies, model weights, .env configuration,
# and configures systemd background services (pithon-daemon and pithon-agent).
#
# Usage:
#   ./scripts/install.sh [options]
#   sudo ./scripts/install.sh [options]
#
# Options:
#   --bot-token <token>        Telegram Bot Token
#   --admin-chat-id <id>       Telegram Admin Chat ID
#   --report-chat-id <id>      Telegram Report / Briefing Chat ID
#   --password <password>      Web Management Portal Password (autogenerated if omitted)
#   --timezone <tz>            Timezone (default: Asia/Kolkata)
#   --user <user>              System user to run services under (default: SUDO_USER or current)
#   --skip-model               Skip downloading GGUF model
#   --skip-services            Skip systemd installation and activation
#   -h, --help                 Show this help message
# ==============================================================================

set -euo pipefail

# ------------------------------------------------------------------------------
# Helpers & Formatting
# ------------------------------------------------------------------------------
BOLD="\033[1m"
GREEN="\033[0;32m"
CYAN="\033[0;36m"
YELLOW="\033[1;33m"
RED="\033[0;31m"
NC="\033[0m"

info() {
    echo -e "${CYAN}==>${NC} ${BOLD}$1${NC}"
}

success() {
    echo -e "${GREEN}==>${NC} ${BOLD}$1${NC}"
}

warn() {
    echo -e "${YELLOW}Warning:${NC} $1"
}

error() {
    echo -e "${RED}Error:${NC} $1" >&2
}

# ------------------------------------------------------------------------------
# Root / Sudo elevation helper
# ------------------------------------------------------------------------------
run_root() {
    if [ "$(id -u)" -eq 0 ]; then
        "$@"
    else
        if command -v sudo >/dev/null 2>&1; then
            sudo "$@"
        else
            error "Root privileges are required for this step, but 'sudo' was not found."
            exit 1
        fi
    fi
}

# ------------------------------------------------------------------------------
# Defaults & CLI Argument Parsing
# ------------------------------------------------------------------------------
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

TARGET_USER="${SUDO_USER:-$USER}"
SKIP_MODEL=false
SKIP_SERVICES=false

CLI_BOT_TOKEN="${TELEGRAM_BOT_TOKEN:-}"
CLI_ADMIN_CHAT_ID="${TELEGRAM_ADMIN_CHAT_ID:-}"
CLI_REPORT_CHAT_ID="${TELEGRAM_REPORT_CHAT_ID:-}"
CLI_PASSWORD="${WEB_ADMIN_PASSWORD:-}"
CLI_TIMEZONE="${TIMEZONE:-Asia/Kolkata}"
PORT="${PORT:-8091}"
DAEMON_PORT="${PITHON_PORT:-8090}"

while [[ $# -gt 0 ]]; do
    case "$1" in
        --bot-token)
            CLI_BOT_TOKEN="$2"
            shift 2
            ;;
        --admin-chat-id)
            CLI_ADMIN_CHAT_ID="$2"
            shift 2
            ;;
        --report-chat-id)
            CLI_REPORT_CHAT_ID="$2"
            shift 2
            ;;
        --password)
            CLI_PASSWORD="$2"
            shift 2
            ;;
        --timezone)
            CLI_TIMEZONE="$2"
            shift 2
            ;;
        --user)
            TARGET_USER="$2"
            shift 2
            ;;
        --skip-model)
            SKIP_MODEL=true
            shift
            ;;
        --skip-services)
            SKIP_SERVICES=true
            shift
            ;;
        -h|--help)
            sed -ne '/^#/!q;s/^# //;2,$p' "$0"
            exit 0
            ;;
        *)
            error "Unknown parameter: $1"
            echo "Run $0 --help for usage details."
            exit 1
            ;;
    esac
done

echo -e "${BOLD}"
echo "  _  ___                     _ "
echo " | |/ / |                   (_)"
echo " | ' /| |__   ___ _ __  _ __ _ "
echo " |  < | '_ \ / _ \ '_ \| '__| |"
echo " | . \| | | |  __/ |_) | |  | |"
echo " |_|\_\_| |_|\___| .__/|_|  |_|"
echo "                 | |           "
echo "                 |_|           "
echo " Autonomous SLM Runtime & Personal Agent"
echo -e "${NC}"

info "Target Repository: ${REPO_DIR}"
info "Service User:      ${TARGET_USER}"

# Verify target user exists
if ! id "$TARGET_USER" >/dev/null 2>&1; then
    error "User '$TARGET_USER' does not exist."
    exit 1
fi

TARGET_HOME=$(getent passwd "$TARGET_USER" | cut -d: -f6)

# ------------------------------------------------------------------------------
# 1. Install System Packages (Debian / Ubuntu / Raspberry Pi OS)
# ------------------------------------------------------------------------------
if command -v apt-get >/dev/null 2>&1; then
    info "Checking required system packages..."
    REQUIRED_PKGS=(
        git
        curl
        python3
        python3-venv
        python3-pip
        python3-dev
        build-essential
        cmake
        tesseract-ocr
    )
    
    MISSING_PKGS=()
    for pkg in "${REQUIRED_PKGS[@]}"; do
        if ! dpkg -s "$pkg" >/dev/null 2>&1; then
            MISSING_PKGS+=("$pkg")
        fi
    done

    if [ ${#MISSING_PKGS[@]} -gt 0 ]; then
        info "Installing missing packages: ${MISSING_PKGS[*]}"
        run_root apt-get update -y
        run_root apt-get install -y --no-install-recommends "${MISSING_PKGS[@]}"
    else
        success "All required system packages are installed."
    fi
else
    warn "Package manager 'apt-get' not found. Please ensure Python 3, venv, tesseract-ocr, and build tools are installed."
fi

# ------------------------------------------------------------------------------
# 2. Virtual Environment Setup
# ------------------------------------------------------------------------------
VENV_DIR="${REPO_DIR}/.venv"
PYTHON_BIN="${VENV_DIR}/bin/python"
PIP_BIN="${VENV_DIR}/bin/pip"

if [ ! -d "$VENV_DIR" ] || [ ! -f "$PYTHON_BIN" ]; then
    info "Creating Python virtual environment in ${VENV_DIR}..."
    if [ "$(id -u)" -eq 0 ] && [ "$TARGET_USER" != "root" ]; then
        su - "$TARGET_USER" -c "python3 -m venv '${VENV_DIR}'"
    else
        python3 -m venv "${VENV_DIR}"
    fi
fi

info "Upgrading pip in virtual environment..."
"$PIP_BIN" install --upgrade pip

# ------------------------------------------------------------------------------
# 3. Install Python Dependencies
# ------------------------------------------------------------------------------
info "Installing llama-cpp-python (using official prebuilt CPU wheels)..."
"$PIP_BIN" install --prefer-binary --extra-index-url https://abetlen.github.io/llama-cpp-python/whl/cpu llama-cpp-python

info "Installing Khepri (pithon) in editable mode..."
"$PIP_BIN" install -e "${REPO_DIR}"

# ------------------------------------------------------------------------------
# 4. Model Download
# ------------------------------------------------------------------------------
MODELS_DIR="${REPO_DIR}/models"
mkdir -p "${MODELS_DIR}"
if [ "$(id -u)" -eq 0 ] && [ "$TARGET_USER" != "root" ]; then
    chown -R "${TARGET_USER}:${TARGET_USER}" "${MODELS_DIR}"
fi

DEFAULT_MODEL_FILE="${MODELS_DIR}/qwen2.5-0.5b-instruct-q4_k_m.gguf"
if [ "$SKIP_MODEL" = false ]; then
    if [ -f "$DEFAULT_MODEL_FILE" ] && [ $(stat -c%s "$DEFAULT_MODEL_FILE" 2>/dev/null || stat -f%z "$DEFAULT_MODEL_FILE" 2>/dev/null || echo 0) -gt 10000000 ]; then
        success "Model already present at ${DEFAULT_MODEL_FILE}"
    else
        info "Downloading default SLM model (Qwen2.5-0.5B)..."
        if [ "$(id -u)" -eq 0 ] && [ "$TARGET_USER" != "root" ]; then
            su - "$TARGET_USER" -c "'${REPO_DIR}/scripts/download_model.sh' qwen '${MODELS_DIR}'"
        else
            "${REPO_DIR}/scripts/download_model.sh" qwen "${MODELS_DIR}"
        fi
    fi
fi

# ------------------------------------------------------------------------------
# 5. Environment Configuration (.env)
# ------------------------------------------------------------------------------
ENV_FILE="${REPO_DIR}/.env"

# Read existing values if present
EXISTING_PASSWORD=""
EXISTING_TOKEN=""
EXISTING_ADMIN=""
EXISTING_REPORT=""
EXISTING_TZ=""

if [ -f "$ENV_FILE" ]; then
    EXISTING_PASSWORD=$(grep -E "^WEB_ADMIN_PASSWORD=" "$ENV_FILE" | cut -d= -f2- | tr -d '"'\'' ' || true)
    EXISTING_TOKEN=$(grep -E "^TELEGRAM_BOT_TOKEN=" "$ENV_FILE" | cut -d= -f2- | tr -d '"'\'' ' || true)
    EXISTING_ADMIN=$(grep -E "^TELEGRAM_ADMIN_CHAT_ID=" "$ENV_FILE" | cut -d= -f2- | tr -d '"'\'' ' || true)
    EXISTING_REPORT=$(grep -E "^TELEGRAM_REPORT_CHAT_ID=" "$ENV_FILE" | cut -d= -f2- | tr -d '"'\'' ' || true)
    EXISTING_TZ=$(grep -E "^TIMEZONE=" "$ENV_FILE" | cut -d= -f2- | tr -d '"'\'' ' || true)
fi

# Determine final values
FINAL_TOKEN="${CLI_BOT_TOKEN:-$EXISTING_TOKEN}"
FINAL_ADMIN="${CLI_ADMIN_CHAT_ID:-$EXISTING_ADMIN}"
FINAL_REPORT="${CLI_REPORT_CHAT_ID:-$EXISTING_REPORT}"
FINAL_TZ="${CLI_TIMEZONE:-${EXISTING_TZ:-Asia/Kolkata}}"

# Autogenerate password if not provided and existing is empty or default template string
FINAL_PASSWORD="${CLI_PASSWORD:-$EXISTING_PASSWORD}"
if [ -z "$FINAL_PASSWORD" ] || [ "$FINAL_PASSWORD" = "set_a_secure_passphrase_here" ] || [ "$FINAL_PASSWORD" = "set_a_secure_web_passphrase" ] || [ "$FINAL_PASSWORD" = "pithon-secure-pass" ]; then
    info "Autogenerating secure Web Admin password..."
    FINAL_PASSWORD=$("$PYTHON_BIN" -c "import secrets; print(secrets.token_urlsafe(16))")
fi

info "Writing configuration to ${ENV_FILE}..."
cat > "${ENV_FILE}" <<EOF
# Khepri Configuration - Generated $(date -u +"%Y-%m-%d %H:%M:%SZ")
TELEGRAM_BOT_TOKEN="${FINAL_TOKEN}"
TELEGRAM_ADMIN_CHAT_ID="${FINAL_ADMIN}"
TELEGRAM_REPORT_CHAT_ID="${FINAL_REPORT}"
WEB_ADMIN_PASSWORD="${FINAL_PASSWORD}"
TIMEZONE="${FINAL_TZ}"
PORT="${PORT}"
PITHON_DAEMON_URL="http://127.0.0.1:${DAEMON_PORT}"
DB_PATH="${REPO_DIR}/data/pithon.db"
EOF

chmod 600 "${ENV_FILE}"
if [ "$(id -u)" -eq 0 ] && [ "$TARGET_USER" != "root" ]; then
    chown "${TARGET_USER}:${TARGET_USER}" "${ENV_FILE}"
fi

# Ensure data directory exists
mkdir -p "${REPO_DIR}/data/notes" "${REPO_DIR}/data/briefings"
if [ "$(id -u)" -eq 0 ] && [ "$TARGET_USER" != "root" ]; then
    chown -R "${TARGET_USER}:${TARGET_USER}" "${REPO_DIR}/data"
fi

# ------------------------------------------------------------------------------
# 6. Systemd Units Installation & Service Launch
# ------------------------------------------------------------------------------
if [ "$SKIP_SERVICES" = false ] && command -v systemctl >/dev/null 2>&1; then
    info "Configuring systemd services for user '${TARGET_USER}'..."

    DAEMON_SERVICE_PATH="/etc/systemd/system/pithon-daemon.service"
    AGENT_SERVICE_PATH="/etc/systemd/system/pithon-agent.service"

    # Write pithon-daemon.service
    cat <<EOF | run_root tee "${DAEMON_SERVICE_PATH}" >/dev/null
[Unit]
Description=Khepri Local SLM Daemon (Raspberry Pi 4/5)
Documentation=https://github.com/pranabeshsingh/Khepri
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=${TARGET_USER}
WorkingDirectory=${REPO_DIR}
Environment=PYTHONUNBUFFERED=1
ExecStart=${REPO_DIR}/.venv/bin/python -m pithon.cli serve --host 127.0.0.1 --port ${DAEMON_PORT} --model models/qwen2.5-0.5b-instruct-q4_k_m.gguf --threads 3
Restart=always
RestartSec=5
OOMScoreAdjust=500

[Install]
WantedBy=multi-user.target
EOF

    # Write pithon-agent.service
    cat <<EOF | run_root tee "${AGENT_SERVICE_PATH}" >/dev/null
[Unit]
Description=Khepri Agent — Telegram Bot, Scheduler, and Web Portal (Raspberry Pi 4/5)
Documentation=https://github.com/pranabeshsingh/Khepri
After=network-online.target pithon-daemon.service
Wants=network-online.target
Requires=pithon-daemon.service

[Service]
Type=simple
User=${TARGET_USER}
WorkingDirectory=${REPO_DIR}
Environment=PYTHONUNBUFFERED=1
Environment=TIMEZONE=${FINAL_TZ}
Environment=PORT=${PORT}
Environment=DB_PATH=data/pithon.db
Environment=PITHON_DAEMON_URL=http://127.0.0.1:${DAEMON_PORT}
ExecStart=${REPO_DIR}/.venv/bin/python -m pithon.agent.main
Restart=always
RestartSec=5
OOMScoreAdjust=500

[Install]
WantedBy=multi-user.target
EOF

    info "Reloading systemd daemon and enabling services..."
    run_root systemctl daemon-reload
    run_root systemctl enable pithon-daemon.service
    run_root systemctl enable pithon-agent.service

    info "Starting pithon-daemon..."
    run_root systemctl restart pithon-daemon.service

    # Wait briefly for daemon health
    info "Waiting for SLM daemon to initialize on port ${DAEMON_PORT}..."
    DAEMON_READY=false
    for i in {1..30}; do
        if curl -s -f "http://127.0.0.1:${DAEMON_PORT}/health" >/dev/null 2>&1; then
            DAEMON_READY=true
            break
        fi
        sleep 1
    done

    if [ "$DAEMON_READY" = true ]; then
        success "Daemon healthy and responding on loopback port ${DAEMON_PORT}."
    else
        warn "Daemon took longer than 30s to report healthy. Check 'journalctl -u pithon-daemon -n 50'."
    fi

    info "Starting pithon-agent..."
    run_root systemctl restart pithon-agent.service

    # Wait briefly for web portal
    AGENT_READY=false
    for i in {1..20}; do
        HTTP_CODE=$(curl -s -o /dev/null -w "%{http_code}" "http://127.0.0.1:${PORT}/" || echo "000")
        if [ "$HTTP_CODE" -eq 200 ] || [ "$HTTP_CODE" -eq 302 ]; then
            AGENT_READY=true
            break
        fi
        sleep 1
    done

    if [ "$AGENT_READY" = true ]; then
        success "Agent Web Portal healthy and responding on port ${PORT}."
    else
        warn "Agent took longer than 20s to respond. Check 'journalctl -u pithon-agent -n 50'."
    fi
fi

# ------------------------------------------------------------------------------
# 7. Summary & Hand-Off
# ------------------------------------------------------------------------------
HOST_IP=$(hostname -I 2>/dev/null | awk '{print $1}' || echo "127.0.0.1")
if [ -z "$HOST_IP" ]; then
    HOST_IP="127.0.0.1"
fi

echo ""
echo -e "${GREEN}======================================================================${NC}"
echo -e "${GREEN}${BOLD}             Khepri Installation Completed Successfully!              ${NC}"
echo -e "${GREEN}======================================================================${NC}"
echo ""
echo -e "  ${BOLD}Web Management Portal:${NC}  http://${HOST_IP}:${PORT}"
echo -e "  ${BOLD}Web Admin Password:${NC}     ${YELLOW}${FINAL_PASSWORD}${NC}"
echo ""
if [ -n "$FINAL_TOKEN" ]; then
    echo -e "  ${BOLD}Telegram Bot:${NC}           Enabled (Admin: ${FINAL_ADMIN:-none}, Reports: ${FINAL_REPORT:-none})"
else
    echo -e "  ${BOLD}Telegram Bot:${NC}           ${YELLOW}Disabled${NC} (Add TELEGRAM_BOT_TOKEN in ${ENV_FILE})"
fi
echo -e "  ${BOLD}SLM Daemon Loopback:${NC}    http://127.0.0.1:${DAEMON_PORT}/health"
echo ""
echo -e "  ${BOLD}Useful Commands:${NC}"
echo -e "    Check services:       ${CYAN}sudo systemctl status pithon-daemon pithon-agent${NC}"
echo -e "    View agent logs:      ${CYAN}journalctl -u pithon-agent -f${NC}"
echo -e "    View daemon logs:     ${CYAN}journalctl -u pithon-daemon -f${NC}"
echo -e "    Test daemon prompt:   ${CYAN}./scripts/query_daemon.sh \"Explain Raft\"${NC}"
echo ""
echo -e "${GREEN}======================================================================${NC}"
