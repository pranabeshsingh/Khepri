"""User profiling and /init onboarding wizard for Khepri."""

import logging
from datetime import datetime, timezone
import zoneinfo
from typing import Any, Optional
from pithon.agent.memory import save_note

logger = logging.getLogger("pithon.profile")


def start_onboarding(
    chat_id: str,
    storage: Any,
    text: str = "",
    tz_name: str = "Asia/Kolkata"
) -> str:
    """Start or fast-track the /init onboarding flow."""
    # Check for fast-track: /init Name | City | Digest | Focus
    parts = [p.strip() for p in text.split("|")]
    if len(parts) >= 2:
        name = parts[0]
        city = parts[1]
        digest = parts[2] if len(parts) > 2 else "Morning 8:30 AM"
        focus = parts[3] if len(parts) > 3 else "Productivity & Engineering"
        return _finalize_profile(chat_id, storage, name, city, digest, focus, tz_name)

    # Multi-step conversational wizard
    if storage:
        storage.set_onboarding_step(chat_id, "name")

    return (
        "👋 *Welcome to Khepri!* Let's personalize your assistant for everyday life.\n\n"
        "1️⃣ *What is your preferred name?* (What should I call you?)\n"
        "_(Type your name or send /cancel to abort)_"
    )


def handle_onboarding_step(
    chat_id: str,
    text: str,
    storage: Any,
    tz_name: str = "Asia/Kolkata"
) -> Optional[str]:
    """Handle an active onboarding step. Returns response string if handled, or None."""
    if not storage:
        return None

    clean = text.strip()
    if clean.lower() in ("/cancel", "cancel", "/abort"):
        storage.clear_onboarding(chat_id)
        return "❌ *Setup cancelled.* You can run `/init` whenever you are ready."

    profile = storage.get_user_profile(chat_id) or {}
    step = profile.get("step")
    if not step:
        return None

    if step == "name":
        name = clean
        storage.save_user_profile(chat_id, name=name, step="city")
        return (
            f"📍 Nice to meet you, *{name}*!\n\n"
            f"2️⃣ *What is your home city or location?*\n"
            f"_(Used for live weather reports, temperature alerts, and localized briefs)_"
        )

    elif step == "city":
        city = clean
        storage.save_user_profile(chat_id, city=city, step="digest")
        return (
            f"⏰ Got it! Location set to *{city}*.\n\n"
            f"3️⃣ *When would you prefer your daily briefings?*\n"
            f"_(e.g., 'Morning 8:30 AM', 'Evening 8:00 PM', or 'None')_"
        )

    elif step == "digest":
        digest = clean
        storage.save_user_profile(chat_id, digest_pref=digest, step="focus")
        return (
            "🎯 Almost done!\n\n"
            "4️⃣ *What is your primary work, project, or daily focus?*\n"
            "_(e.g. 'Software Engineering', 'Product Design', 'Fitness', 'Cloud Architecture')_"
        )

    elif step == "focus":
        focus = clean
        name = profile.get("name") or "Friend"
        city = profile.get("city") or "Kolkata"
        digest = profile.get("digest_pref") or "Morning 8:30 AM"
        return _finalize_profile(chat_id, storage, name, city, digest, focus, tz_name)

    return None


def _finalize_profile(
    chat_id: str,
    storage: Any,
    name: str,
    city: str,
    digest_pref: str,
    focus: str,
    tz_name: str
) -> str:
    """Save finalized profile, create markdown note, and clear onboarding step."""
    if storage:
        storage.save_user_profile(
            chat_id,
            name=name,
            city=city,
            digest_pref=digest_pref,
            focus=focus
        )
        storage.clear_onboarding(chat_id)

    try:
        now_str = datetime.now(zoneinfo.ZoneInfo(tz_name)).strftime("%Y-%m-%d %H:%M %Z")
    except Exception:
        now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    note_content = (
        f"# User Profile: {name}\n\n"
        f"- **Name:** {name}\n"
        f"- **Home Location:** {city}\n"
        f"- **Daily Briefing Preference:** {digest_pref}\n"
        f"- **Primary Focus:** {focus}\n"
        f"- **Timezone:** {tz_name}\n"
        f"- **Last Updated:** {now_str}\n\n"
        f"---\n"
        f"*Auto-generated by Khepri `/init` setup wizard. Editable anytime in Knowledge Memory.*\n"
    )
    save_note("user-profile", note_content, tz_name=tz_name, base_dir=(storage.notes_dir() if storage else None))

    return (
        f"🎉 *Setup Complete! Your profile is active:*\n\n"
        f"• 👤 *Name:* {name}\n"
        f"• 📍 *Location:* {city}\n"
        f"• ⏰ *Briefings:* {digest_pref}\n"
        f"• 🎯 *Primary Focus:* {focus}\n\n"
        f"📝 _Saved to Knowledge Memory as `user-profile.md`._\n"
        f"I will now personalize all conversations and default weather lookups for you!"
    )


def format_user_profile_prompt_header(storage: Any, chat_id: str) -> str:
    """Format user profile block for LLM system prompt injection."""
    if not storage:
        return ""
    profile = storage.get_user_profile(chat_id)
    if not profile or not profile.get("name"):
        return ""

    name = profile.get("name")
    city = profile.get("city") or "Kolkata"
    focus = profile.get("focus") or ""
    header_lines = [
        "[User Profile]",
        f"Name: {name}",
        f"Home Location: {city}"
    ]
    if focus:
        header_lines.append(f"Primary Focus: {focus}")
    header_lines.append(
        f"(Instruction: Address the user naturally as {name} when relevant. "
        f"Default generic weather queries to {city}.)\n"
    )
    return "\n".join(header_lines)


def get_default_weather_city(storage: Any, chat_id: str, fallback: str = "Kolkata") -> str:
    """Get the user's home city for weather lookups, falling back to default."""
    if not storage:
        return fallback
    profile = storage.get_user_profile(chat_id)
    if profile and profile.get("city"):
        return profile["city"].strip()
    return fallback
